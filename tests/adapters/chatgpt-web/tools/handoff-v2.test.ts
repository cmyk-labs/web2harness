const tools: CodexTool[] = [
  { name: "read_value", namespace: "fixture", description: "Read", parameters: { type: "object" } },
  { name: "exec", namespace: "functions", description: "Code", parameters: {}, freeform: true },
];
const call = { name: "read_value", namespace: "fixture", arguments: { z: [1, 2], a: " x\r\n" } };
const v2 = () => new ToolBatchHandoff(tools, {}, false, { protocol: HANDOFF_V2 });
const environment = (root: string) => ({ cwd: root, roots: [root], writableRoots: [],
  sandboxPolicy: { type: "readOnly" as const, networkAccess: false }, tools });
function fixture() {
  const parent = resolve(tmpdir()), root = mkdtempSync(join(parent, "w2h-handoff-v2-"));
  return { root, cleanup() {
    if (dirname(resolve(root)) !== parent || !root.startsWith(join(parent, "w2h-handoff-v2-"))) throw Error("Fixture ownership mismatch");
    rmSync(root, { recursive: true, force: true });
  } };
}

test("v2 host identity ignores object key order, scopes retries to this round, and rejects caller IDs", () => {
  const round = v2(), first = round.submit(undefined, [call]);
  expect(first.protocol).toBe(HANDOFF_V2);
  expect(first.submission_id).toMatch(/^submission_[a-f0-9]{64}$/);
  expect(round.submit(undefined, [{ arguments: { a: " x\r\n", z: [1, 2] }, namespace: "fixture", name: "read_value" }])).toEqual(first);
  expect(v2().submit(undefined, [call]).submission_id).not.toBe(first.submission_id);
  expect(() => round.submit(first.submission_id, [call])).toThrow("generated by the host");
  expect(() => round.submit(undefined, [{ ...call, arguments: { z: [2, 1], a: " x\r\n" } }])).toThrow("different batch");
  expect(() => round.submit(undefined, [{ ...call, arguments: { z: [1, 2], a: " x\n" } }])).toThrow("different batch");
});

test("v2 preserves code bytes and physical/durable delivery fences including cancellation", () => {
  const round = v2(), input = "const x = '  exact';\r\ntext(x);\n";
  const batch = [{ name: "exec", namespace: "functions", input }];
  const receipt = round.submit(undefined, batch);
  expect(() => round.takeForDelivery(() => {})).toThrow("not physically settled");
  round.seal(receipt.batch_id); round.confirmPhysicalSettlement();
  expect(() => round.takeForDelivery(() => { throw Error("disk full"); })).toThrow("disk full");
  let writes = 0;
  expect(round.takeForDelivery(record => { writes++; expect(record.protocol).toBe(HANDOFF_V2); })[0]?.input).toBe(input);
  round.takeForDelivery(() => { writes++; }); expect(writes).toBe(1);
  expect(() => round.submit(undefined, [{ ...batch[0]!, input: input.replace("\r\n", "\n") }])).toThrow("different batch");
  round.cancel(); expect(() => round.submit(undefined, batch)).toThrow("cancelled");
  expect(() => round.takeForDelivery(() => {})).toThrow("cancelled");
});

test("v2 rejects bad identity and policy atomically; v1 keeps its required caller ID", () => {
  const round = new ToolBatchHandoff(tools, { parallelToolCalls: false }, false, { protocol: HANDOFF_V2 });
  expect(() => round.submit(undefined, [call, call])).toThrow("parallel_tool_calls");
  expect(() => round.submit(undefined, [{ ...call, namespace: "wrong" }])).toThrow("identity");
  expect(round.roundState.round_state).toBe("open");
  expect(round.submit(undefined, [call]).call_ids).toHaveLength(1);
  const old = new ToolBatchHandoff(tools);
  expect(() => old.submit(undefined, [call])).toThrow("Invalid handoff submission_id");
  expect(old.submit("v1-client-id", [call]).submission_id).toBeUndefined();
});

test("nested gateway identity uses canonical wire objects without rewriting the first generated code", () => {
  const env = environment(resolve(tmpdir())), round = v2();
  const a = [{ scope: "exec" as const, name: "exec_command", arguments: { z: [1, 2], a: " x\r\n" } }];
  const b = [{ arguments: { a: " x\r\n", z: [1, 2] }, name: "exec_command", scope: "exec" as const }];
  const original = handoffCalls(env, "native", a), reordered = handoffCalls(env, "native", b);
  expect(original[0]?.input).toBe(reordered[0]?.input);
  const receipt = round.submit(undefined, original);
  expect(round.submit(undefined, reordered)).toEqual(receipt);
  round.seal(receipt.batch_id); round.confirmPhysicalSettlement();
  expect(round.takeForDelivery(() => {})[0]?.input).toBe(original[0]?.input);
});

for (const manual of [false, true]) test(`v2 ${manual ? "safe" : "native"} MCP catalog, binding, atomic submission and fences`, async () => {
  const f = fixture(), broker = TurnBroker.forSocket(defaultBrokerEndpoint(f.root));
  const contract = manual ? "safe" : "native", nonce = "fixture_v2_surface_0123456789";
  const server = createHandoffMcpServer({ brokerSocketPath: broker.socketPath, contract, protocol: HANDOFF_V2 });
  const client = new Client({ name: "v2-fixture", version: "1" });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  try {
    const token = await broker.registerHandoff(environment(f.root), { protocol: HANDOFF_V2,
      ...(manual ? { surfaceNonce: nonce } : {}), policy: { parallelToolCalls: false } });
    const reference = manual ? { request_id: token } : { turn_token: token };
    await server.connect(serverTransport); await client.connect(clientTransport);
    expect(client.getInstructions()).toContain(HANDOFF_V2);
    const listed = await client.listTools();
    expect(listed.tools.some(t => t.name === "codex_submit_tool_call")).toBeFalse();
    expect(listed.tools.find(t => t.name === "codex_submit_tool_call_v2")?.inputSchema.properties).not.toHaveProperty("submission_id");
    await expect(callTurnBroker(broker.socketPath, { method: "claim", token, protocol: HANDOFF_V1, contract })).rejects.toThrow("protocol mismatch");
    if (manual) {
      await client.callTool({ name: "codex_turn_start", arguments: reference });
      expect(() => broker.confirmSafeTurnSent(token, nonce + "wrong")).toThrow("binding");
      broker.confirmSafeTurnSent(token, nonce);
    }
    const inventory = await client.callTool({ name: "codex_tool_inventory", arguments: reference });
    expect(inventory.structuredContent).toMatchObject({ protocol: HANDOFF_V2, submission_identity: "host", submission_tool: "codex_submit_tool_call_v2" });
    expect((await client.callTool({ name: "codex_submit_tool_call_v2", arguments: { ...reference, submission_id: "stale", call } })).isError).toBeTrue();
    expect((await client.callTool({ name: "codex_submit_tool_call", arguments: { ...reference, submission_id: "stale", call } })).isError).toBeTrue();
    const accepted = await client.callTool({ name: "codex_submit_tool_call_v2", arguments: { ...reference, call } });
    expect(accepted.isError).not.toBeTrue();
    expect(accepted.structuredContent).toMatchObject({ protocol: HANDOFF_V2, sealed: true, execution_state: "not_executed" });
    const replay = await client.callTool({ name: "codex_submit_tool_call_v2", arguments: { ...reference, call } });
    expect(replay.structuredContent).toEqual(accepted.structuredContent);
    expect(() => broker.confirmHandoffPhysicalSettlement(token)).toThrow("fence");
    const ready = broker.beginCompletionFence(token); if (!("revision" in ready)) throw Error("Expected ready fence");
    expect(broker.commitCompletionFence(token, ready.revision)).toMatchObject({ state: "committed" });
    expect(() => broker.takeHandoffBatch(token, () => {})).toThrow("not physically settled");
    broker.confirmHandoffPhysicalSettlement(token);
    expect(() => broker.takeHandoffBatch(token, () => { throw Error("disk full"); })).toThrow("disk full");
    expect(broker.takeHandoffBatch(token, () => {})[0]?.arguments).toEqual(call.arguments);
    broker.revoke(token);
    expect((await client.callTool({ name: "codex_submit_tool_call_v2", arguments: { ...reference, call } })).isError).toBeTrue();
  } finally { await client.close(); await server.close(); await broker.close(); f.cleanup(); }
});

test("remote owners and stdio explicitly select v2, and cannot claim v1 tokens", async () => {
  const f = fixture(), broker = TurnBroker.forSocket(defaultBrokerEndpoint(f.root));
  const client = new Client({ name: "v2-stdio-fixture", version: "1" });
  try {
    const old = await broker.registerHandoff(environment(f.root));
    const owner = new RemoteTurnBroker(broker.socketPath);
    const token = await owner.registerHandoff(environment(f.root), { protocol: HANDOFF_V2 });
    await client.connect(new StdioClientTransport({ command: process.execPath, cwd: process.cwd(), stderr: "pipe",
      args: ["src/cli.ts", "mcp", "--broker-socket", broker.socketPath, "--protocol", HANDOFF_V2] }));
    expect(client.getInstructions()).toContain(HANDOFF_V2);
    expect((await client.callTool({ name: "codex_tool_inventory", arguments: { turn_token: old } })).isError).toBeTrue();
    expect((await client.callTool({ name: "codex_finish_turn", arguments: { turn_token: token, final_answer: "fixture final" } })).isError).not.toBeTrue();
    expect(await owner.waitForHandoffIntent(token)).toEqual({ kind: "final", answer: "fixture final" });
  } finally { await client.close(); await broker.close(); f.cleanup(); }
}, 20_000);

test("explicit configuration reaches transport and prompt; v1 stays default and unsupported protocols fail", () => {
  expect(handoffProtocol()).toBe(HANDOFF_V1); expect(() => handoffProtocol("latest")).toThrow("Unsupported");
  const before = defaultConfig("mcp-bridge"), after = { ...before, mcpHandoffProtocol: HANDOFF_V2 };
  expect(mcpCommand(before)).toContain(HANDOFF_V1); expect(mcpCommand(after)).toContain(HANDOFF_V2);
  expect(tunnelWorkerRuntimeChanged(before, after)).toBeTrue();
  expect(providerConfig(after).chatgptWeb?.mcpHandoffProtocol).toBe(HANDOFF_V2);
  const parsed = parseRequest({ model: "gpt-5.6-sol", input: "read fixture", parallel_tool_calls: false });
  const prompt = compileChatGptWebPrompt(parsed, { localToolsEnabled: true, solAvailable: true, extraHighAvailable: false, proAvailable: false }, "fixture_current_token_0123456789",
    { toolBatchHandoff: true, handoffProtocol: HANDOFF_V2 });
  expect(prompt.text).toContain(`Protocol ${HANDOFF_V2}`); expect(prompt.text).toContain("codex_submit_tool_call_v2");
  expect(prompt.text).toContain("Do not generate or supply submission_id");
  expect(prompt.text).toContain("use codex_submit_tool_call_v2 with one call object");
  expect(prompt.text).not.toContain("use codex_submit_tool_call with one call object");
});
